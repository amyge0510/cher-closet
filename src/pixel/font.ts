export const GLYPH_ROWS = 7;

export function glyph(ch: string): string[] {
  return G[ch.toUpperCase()] ?? G["?"];
}

export const GLYPHS = G;

// Lays out text as a list of lit cells, in font-pixel units.
export function layoutText(text: string, opts: { bold?: boolean; spacing?: number } = {}) {
  const spacing = opts.spacing ?? 1;
  const cells: [number, number][] = [];
  let x = 0;
  for (const ch of text) {
    const g = glyph(ch);
    const w = g[0].length;
    for (let r = 0; r < GLYPH_ROWS; r++) {
      for (let c = 0; c < w; c++) {
        if (g[r][c] !== "#") continue;
        cells.push([x + c, r]);
        if (opts.bold) cells.push([x + c + 1, r]);
      }
    }
    x += w + (opts.bold ? 1 : 0) + spacing;
  }
  return { cells, width: Math.max(0, x - spacing), height: GLYPH_ROWS };
}

// Splits text into lines no wider than maxWidth font pixels, breaking at spaces.
export function wrapText(text: string, maxWidth: number, opts: { bold?: boolean } = {}): string[] {
  const lines: string[] = [];
  let line = "";
  for (const word of text.split(/\s+/).filter(Boolean)) {
    const next = line ? `${line} ${word}` : word;
    if (line && layoutText(next, opts).width > maxWidth) {
      lines.push(line);
      line = word;
    } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}
